import { jsPDF } from 'jspdf';
import { SECTION_LABELS, SECTION_ORDER, formatDate, primaryTitle, wordCount } from './utils';

// jsPDF's built-in fonts only support WinAnsi characters; strip anything else.
const clean = (s = '') =>
  String(s)
    .replace(/[‐-‒]/g, '-')
    .replace(/[^\x09\x0A\x20-\x7E\xA0-\xFF–—‘’“”•]/g, '');

const COLORS = {
  navy: [10, 16, 48],
  violet: [124, 58, 237],
  blue: [59, 130, 246],
  text: [30, 41, 59],
  muted: [100, 116, 139],
};

/**
 * Build and download a PDF for the given research project.
 * @param research  saved research object
 * @param sections  which sections to include (defaults to all)
 */
export function downloadResearchPdf(research, sections = SECTION_ORDER, filename) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  const M = 56;
  const contentW = W - M * 2;
  let y = 0;

  const header = () => {
    doc.setFillColor(...COLORS.navy);
    doc.rect(0, 0, W, 64, 'F');
    doc.setFillColor(...COLORS.violet);
    doc.rect(0, 64, W * 0.55, 3, 'F');
    doc.setFillColor(...COLORS.blue);
    doc.rect(W * 0.55, 64, W * 0.45, 3, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(15);
    doc.text('ResearchMate AI', M, 36);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor(196, 181, 253);
    doc.text('Smart Research Assistant', M, 50);
  };

  const footer = (page, total) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(...COLORS.muted);
    doc.text(
      'Generated by ResearchMate AI. Methods and outcomes are proposed, not completed research.',
      M,
      H - 28
    );
    doc.text(`Page ${page} of ${total}`, W - M, H - 28, { align: 'right' });
  };

  const ensure = (needed) => {
    if (y + needed > H - 60) {
      doc.addPage();
      header();
      y = 100;
    }
  };

  const paragraph = (text, { size = 11, bold = false, color = COLORS.text, indent = 0, gap = 6, lineH = 1.45 } = {}) => {
    doc.setFont('helvetica', bold ? 'bold' : 'normal');
    doc.setFontSize(size);
    doc.setTextColor(...color);
    const lines = doc.splitTextToSize(clean(text), contentW - indent);
    const lh = size * lineH;
    lines.forEach((line) => {
      ensure(lh);
      doc.text(line, M + indent, y);
      y += lh;
    });
    y += gap;
  };

  const heading = (label) => {
    ensure(46);
    y += 8;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(...COLORS.violet);
    doc.text(clean(label.toUpperCase()), M, y);
    y += 6;
    doc.setDrawColor(...COLORS.violet);
    doc.setLineWidth(1);
    doc.line(M, y, M + 40, y);
    doc.setDrawColor(226, 232, 240);
    doc.line(M + 40, y, W - M, y);
    y += 18;
  };

  const numbered = (items) => {
    items.forEach((item, i) => {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(11);
      const lines = doc.splitTextToSize(clean(item), contentW - 26);
      ensure(lines.length * 16 + 4);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(...COLORS.blue);
      doc.text(`${i + 1}.`, M, y);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(...COLORS.text);
      lines.forEach((line) => {
        doc.text(line, M + 26, y);
        y += 16;
      });
      y += 4;
    });
  };

  // ---------- first page ----------
  header();
  y = 108;

  const full = sections.length === SECTION_ORDER.length;
  if (full) {
    paragraph(primaryTitle(research), { size: 20, bold: true, color: COLORS.navy, gap: 8, lineH: 1.25 });
  } else {
    paragraph(SECTION_LABELS[sections[0]], { size: 20, bold: true, color: COLORS.navy, gap: 8, lineH: 1.25 });
  }
  paragraph(
    `Domain: ${research.domain}   |   Level: ${research.level}   |   ${formatDate(research.createdAt)}`,
    { size: 9, color: COLORS.muted, gap: 4 }
  );
  paragraph(`Project idea: ${research.idea}`, { size: 10, color: COLORS.muted, gap: 10 });

  sections.forEach((key) => {
    const d = research.data[key];
    if (!d) return;
    heading(SECTION_LABELS[key]);
    if (key === 'abstract') {
      paragraph(d, { size: 11, lineH: 1.55, gap: 4 });
      paragraph(`${wordCount(d)} words`, { size: 8, color: COLORS.muted });
    } else if (key === 'keywords') {
      paragraph(d.join('  |  '), { size: 11, bold: true, color: COLORS.blue });
    } else {
      numbered(d);
    }
  });

  const total = doc.getNumberOfPages();
  for (let p = 1; p <= total; p++) {
    doc.setPage(p);
    footer(p, total);
  }

  const slug =
    filename ||
    (full
      ? `researchmate-${clean(primaryTitle(research)).toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 50)}`
      : `researchmate-${sections[0].replace('_', '-')}`);
  doc.save(`${slug.replace(/^-+|-+$/g, '')}.pdf`);
}
