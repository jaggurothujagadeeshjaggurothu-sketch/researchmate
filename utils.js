export const DOMAINS = [
  'AI / Machine Learning',
  'Internet of Things (IoT)',
  'Web Development',
  'Cybersecurity',
  'Data Science',
  'Cloud Computing',
  'Other',
];

export const LEVELS = ['Beginner', 'Intermediate', 'Advanced'];

export const EXAMPLE_IDEAS = [
  { domain: 'AI / Machine Learning', text: 'Detect fake news using machine learning.' },
  { domain: 'Internet of Things (IoT)', text: 'Smart irrigation system that predicts soil moisture using IoT sensors.' },
  { domain: 'Cybersecurity', text: 'Detect phishing websites in real time with a browser extension.' },
];

export const EMPTY_FORM = {
  idea: '',
  domain: DOMAINS[0],
  tech: '',
  level: 'Intermediate',
};

export const SECTION_LABELS = {
  titles: 'Research Title Options',
  abstract: 'Abstract',
  keywords: 'Keywords',
  objectives: 'Research Objectives',
  future_enhancements: 'Future Enhancements',
};

export const SECTION_ORDER = ['titles', 'abstract', 'keywords', 'objectives', 'future_enhancements'];

export const uid = () =>
  (crypto?.randomUUID?.() ?? `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`);

export const wordCount = (text = '') => text.trim().split(/\s+/).filter(Boolean).length;

export const formatDate = (iso) =>
  new Date(iso).toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' });

export const primaryTitle = (research) =>
  research.data.titles?.[research.selectedTitle ?? 0] || research.data.titles?.[0] || 'Untitled research';

/** Plain-text version of one section (used for copy). */
export function sectionToText(research, key) {
  const d = research.data;
  switch (key) {
    case 'titles':
      return d.titles.map((t, i) => `${i + 1}. ${t}`).join('\n');
    case 'abstract':
      return d.abstract;
    case 'keywords':
      return d.keywords.join(', ');
    case 'objectives':
      return d.objectives.map((t, i) => `${i + 1}. ${t}`).join('\n');
    case 'future_enhancements':
      return d.future_enhancements.map((t, i) => `${i + 1}. ${t}`).join('\n');
    default:
      return '';
  }
}

export function fullToText(research) {
  const header = `${primaryTitle(research)}\nDomain: ${research.domain} | Level: ${research.level}\n`;
  const body = SECTION_ORDER.map(
    (k) => `${SECTION_LABELS[k].toUpperCase()}\n${sectionToText(research, k)}`
  ).join('\n\n');
  return `${header}\n${body}\n\nGenerated by ResearchMate AI`;
}

export async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    try {
      const ta = document.createElement('textarea');
      ta.value = text;
      ta.style.position = 'fixed';
      ta.style.opacity = '0';
      document.body.appendChild(ta);
      ta.select();
      const ok = document.execCommand('copy');
      document.body.removeChild(ta);
      return ok;
    } catch {
      return false;
    }
  }
}

/** Friendly follow-up hint for known backend error codes. */
export function errorHint(code) {
  switch (code) {
    case 'ollama_unreachable':
      return 'Start Ollama with:  ollama serve';
    case 'model_missing':
      return 'Install the model with:  ollama pull llama3.2';
    case 'backend_unreachable':
      return 'Start the backend with:  uvicorn main:app --reload --port 8000';
    case 'gemini_key_missing':
      return 'Add GEMINI_API_KEY to backend/.env and restart the backend, or switch to Ollama in Settings.';
    default:
      return null;
  }
}
