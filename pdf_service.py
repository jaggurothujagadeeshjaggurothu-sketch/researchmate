"""PDF export for ResearchMate AI (fpdf2, core fonts -> text is sanitised to latin-1)."""
from __future__ import annotations

from datetime import datetime

from fpdf import FPDF

from ai_service import SECTION_LABELS

_REPLACE = {
    "‘": "'", "’": "'", "“": '"', "”": '"', "–": "-", "—": "-",
    "…": "...", "•": "-", " ": " ", "→": "->", "≥": ">=", "≤": "<=",
}


def clean(text: str) -> str:
    for k, v in _REPLACE.items():
        text = text.replace(k, v)
    return text.encode("latin-1", "replace").decode("latin-1")


class _PDF(FPDF):
    def header(self):
        self.set_fill_color(10, 16, 36)
        self.rect(0, 0, 210, 26, "F")
        self.set_fill_color(124, 92, 255)
        self.rect(0, 26, 210, 1.2, "F")
        self.set_xy(15, 8)
        self.set_font("Helvetica", "B", 16)
        self.set_text_color(255, 255, 255)
        self.cell(0, 8, "ResearchMate AI")
        self.set_xy(15, 16)
        self.set_font("Helvetica", "", 9)
        self.set_text_color(170, 185, 255)
        self.cell(0, 5, "Smart Research Assistant - AI-generated research proposal")
        self.set_y(34)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(130, 130, 150)
        self.cell(0, 8, f"Generated by ResearchMate AI - Page {self.page_no()}", align="C")


def _heading(pdf: _PDF, text: str):
    pdf.ln(3)
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(91, 60, 220)
    pdf.cell(0, 8, clean(text.upper()), new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(124, 92, 255)
    pdf.line(15, pdf.get_y(), 195, pdf.get_y())
    pdf.ln(3)
    pdf.set_text_color(30, 30, 45)


def _bullets(pdf: _PDF, items: list[str], numbered: bool = True):
    pdf.set_font("Helvetica", "", 11)
    for i, it in enumerate(items, 1):
        pdf.set_x(15)
        pdf.multi_cell(0, 6.5, clean(f"{i}. {it}" if numbered else f"- {it}"),
                       new_x="LMARGIN", new_y="NEXT")
        pdf.ln(1.5)


def build_pdf(entry: dict) -> bytes:
    r = entry["result"]
    pdf = _PDF(format="A4")
    pdf.set_margins(15, 15, 15)
    pdf.set_auto_page_break(True, 18)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 15)
    pdf.set_text_color(20, 20, 40)
    pdf.multi_cell(0, 8, clean(r["titles"][0]), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(110, 110, 130)
    meta = f'Domain: {entry["domain"]}  |  Level: {entry["level"]}  |  {entry["created"]}'
    if entry.get("tech"):
        meta += f'  |  Tech: {entry["tech"]}'
    pdf.multi_cell(0, 5, clean(meta), new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(30, 30, 45)

    _heading(pdf, "Project Idea")
    pdf.set_font("Helvetica", "I", 11)
    pdf.multi_cell(0, 6.5, clean(entry["idea"]), new_x="LMARGIN", new_y="NEXT")

    _heading(pdf, SECTION_LABELS["titles"])
    _bullets(pdf, r["titles"])
    _heading(pdf, SECTION_LABELS["abstract"])
    pdf.set_font("Helvetica", "", 11)
    pdf.multi_cell(0, 6.5, clean(r["abstract"]), align="J", new_x="LMARGIN", new_y="NEXT")
    _heading(pdf, SECTION_LABELS["keywords"])
    pdf.set_font("Helvetica", "B", 11)
    pdf.multi_cell(0, 6.5, clean("  |  ".join(r["keywords"])), new_x="LMARGIN", new_y="NEXT")
    _heading(pdf, SECTION_LABELS["objectives"])
    _bullets(pdf, r["objectives"])
    _heading(pdf, SECTION_LABELS["future_enhancements"])
    _bullets(pdf, r["future_enhancements"])

    pdf.ln(4)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(130, 130, 150)
    pdf.multi_cell(0, 4.5, "AI-generated draft. Methods and outcomes are proposed, not completed research. "
                           "Review and verify before academic use.", new_x="LMARGIN", new_y="NEXT")
    return bytes(pdf.output())
